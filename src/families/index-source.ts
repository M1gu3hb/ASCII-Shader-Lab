import type { FamilyIndexEntry, FamilyMeta } from './types';

/** The index entry of a family (registry.ts): what every page knows of it without its spec. */
export function indexEntry(f: FamilyMeta): FamilyIndexEntry {
  return {
    id: f.id, name: f.name, group: f.group, kind: f.kind, v: f.version, loop: f.caps.loop,
    ...(f.color ? { color: true as const } : {}),
    ...(f.color && f.kind !== 'analytic' ? { colorSince: f.colorSince ?? 1 } : {}),
  };
}

/** The source of src/families/index-data.ts for a list of families (scripts/families-index.ts). */
export function indexSource(families: readonly FamilyMeta[]): string {
  return `import type { FamilyIndexEntry } from './types';

/**
 * Generated by scripts/families-index.ts from the families' specs: never edit by hand
 * (tests/unit/families-index.test.ts checks it). What every page knows of each family without its spec.
 */
export const FAMILY_INDEX: readonly FamilyIndexEntry[] = [
${families.map(f => '  ' + JSON.stringify(indexEntry(f)) + ',').join('\n')}
];
`;
}
